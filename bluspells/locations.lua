local function is_horizon_zone(zone_id)
    zone_id = tonumber(zone_id);
    if not zone_id then return false; end

    -- Zone IDs 1-252 contain the four supported-era expansions plus several
    -- later additions handled explicitly above.  253+ is Abyssea/Adoulin/
    -- Escha/Reisenjima and later retail content.
    if zone_id < 1 or zone_id > 252 then return false; end
    return excluded_later_zone_ids[zone_id] ~= true;
end

local function normalize_name(value)
    return tostring(value or ''):lower():gsub('[^%w]+', ' '):gsub('^%s+', ''):gsub('%s+$', '');
end

local function build_cache()
    if cache_ready then return; end
    cache_ready = true;

    local rm = AshitaCore and AshitaCore:GetResourceManager() or nil;
    if not rm then return; end

    for id, _ in pairs(records) do
        local spell = rm:GetSpellById(id);
        if spell and spell.Name and spell.Name[1] then
            cache[normalize_name(spell.Name[1])] = id;
        end
    end

    for name, id in pairs(name_aliases) do
        cache[name] = id;
    end
end

function locations.get(spell_name)
    build_cache();
    local id = cache[normalize_name(spell_name)];
    if not id then return nil; end

    local source = records[id];
    if not source then return nil; end

    local filtered = {};
    for _, entry in ipairs(source) do
        if entry and is_horizon_zone(entry.zone) then
            table.insert(filtered, entry);
        end
    end
    return filtered;
end

function locations.get_zone_name(zone_id)
    local rm = AshitaCore and AshitaCore:GetResourceManager() or nil;
    if not rm then return ('Zone %d'):format(tonumber(zone_id) or 0); end
    return rm:GetString('zones.names', tonumber(zone_id) or 0) or ('Zone %d'):format(tonumber(zone_id) or 0);
end

return locations;
